-- ============================================================================
-- 邻伴 · CI MySQL 初始化脚本
-- ============================================================================
-- 目的：在 MySQL 容器**首次初始化**时把时区与字符集设成生产口径。
--
-- 为什么必须在初始化阶段做：
--   ① 时区：`TZ=UTC` 只影响容器进程的 TZ 环境变量，**不改 MySQL 的
--      @@global.time_zone**（默认跟随系统 = UTC，但容器里可能是 LOCAL）。
--      订单时段、券有效期、结算日界全部按 MySQL 的时区算 →
--      时区错 = 跨时区订单时段错位，且不报错，很难发现。
--   ② 字符集：数据库默认字符集决定所有表列的默认字符集。
--      utf8mb3 存不了 emoji 与生僻字（社区名、陪聊员昵称、评价内容）
--      → 插入时直接报错或截断。
--
-- 口径与 docker-compose.yml 完全一致（不要两边写成不同值）：
--   时区   = +00:00（UTC）
--   字符集 = utf8mb4 / utf8mb4_0900_ai_ci
--
-- ⚠️ 注意：MySQL 官方镜像**只在数据目录为空时**执行本目录下的脚本。
--    容器重建（数据卷还在）时不会重跑 → 此时需手动执行：
--      ALTER DATABASE linban CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
--      SET GLOBAL time_zone = '+00:00';
-- ============================================================================

-- ① 全局时区固定为 UTC（+00:00 表示 UTC 偏移，不用命名时区，避免夏令时歧义）
SET GLOBAL time_zone = '+00:00';

-- ② 建库并指定字符集（CI 里 MYSQL_DATABASE 已建库，但字符集要在这里纠正）
--    IF NOT EXISTS：容器初始化时 MYSQL_DATABASE 已先建好，这里只是确保字符集正确
ALTER DATABASE `linban` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

-- ③ 会话级也设成 UTC（让本脚本内的所有查询按 UTC 解释时间戳）
SET time_zone = '+00:00';
